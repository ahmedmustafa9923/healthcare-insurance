#!/usr/bin/env bash
# Writes imports.tf: adopts the Sep 26 carrier resources into Terraform state.
# Format per module: <module_name> <carrier-lob> <bucket hex suffix> <random_id base64url>
set -euo pipefail
ACCOUNT=308281188883

carriers=(
  "all_state_personal  all-state-personal  0821f669 CCH2aQ"
  "all_state_business  all-state-business  2dea55b2 LepVsg"
  "blue_cross_personal blue-cross-personal e42ee6f3 5C7m8w"
  "blue_cross_business blue-cross-business b952986e uVKYbg"
  "hartford_personal   hartford-personal   9e8170a9 noFwqQ"
  "hartford_business   hartford-business   5192788f UZJ4jw"
)

imp() { printf 'import {\n  to = %s\n  id = "%s"\n}\n\n' "$1" "$2"; }

{
  echo "# Generated by gen_imports.sh — adopts resources created before remote state existed."
  echo "# Safe to delete after a successful apply."
  echo
  for row in "${carriers[@]}"; do
    read -r mod name hex b64 <<<"$row"
    m="module.$mod"
    bucket="health-app-$name-$hex"
    lg="/aws/ecs/$name"
    echo "# ---------- $name ----------"
    imp "$m.random_id.bucket_suffix"                                         "$b64"
    imp "$m.aws_s3_bucket.carrier_storage"                                   "$bucket"
    imp "$m.aws_s3_bucket_server_side_encryption_configuration.encryption"   "$bucket"
    imp "$m.aws_s3_bucket_public_access_block.public_block"                  "$bucket"
    imp "$m.aws_iam_role.app_role"                                           "app-execution-role-$name"
    imp "$m.aws_cloudwatch_log_group.carrier_log_group"                      "$lg"
    imp "$m.aws_cloudwatch_log_stream.carrier_stream"                        "$lg:app-runtime-core"
    imp "$m.aws_cloudwatch_log_metric_filter.error_filter"                   "$lg:$name-error-filter"
    imp "$m.aws_cloudwatch_metric_alarm.application_error_alarm"             "critical-error-alarm-$name"
  done
  echo "# ---------- shared monitoring ----------"
  imp "aws_sns_topic.alerts"                   "arn:aws:sns:us-east-1:$ACCOUNT:healthcare-alerts"
  imp "aws_cloudwatch_metric_alarm.cpu_high"     "healthcare-server-cpu-high"
  imp "aws_cloudwatch_metric_alarm.status_check" "healthcare-server-status-check"
  imp "aws_cloudwatch_dashboard.healthcare"      "healthcare-server"
} > imports.tf

echo "Wrote $(grep -c '^import' imports.tf) import blocks to imports.tf"
